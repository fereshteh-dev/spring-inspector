class DocumentComposerTest {

    private static final Clock CLOCK = Clock.fixed(Instant.parse("2026-11-12T10:00:00Z"), ZoneOffset.UTC);
    private static final DetectedVersions VERSIONS = new DetectedVersions(
            Optional.of(Version.of(25, 0, 0)), Optional.of(Version.of(4, 1, 1)), Optional.of(Version.of(2, 0, 1)));

    private final DocumentComposer composer = new DocumentComposer("1.2.3", CLOCK);

    @Test
    void namesTheProjectAndSaysWhenAndByWhatItWasGenerated() {
        Document document = composer.compose(facts(SampleProject.shop(), Optional.empty()));

        assertThat(document.title()).isEqualTo("shop-service: project document");
        assertThat(document.subtitle()).isEqualTo("Generated by Spring Inspector 1.2.3 on 2026-11-12");
    }

    @Test
    void summarisesWhatTheApplicationDoesInOneParagraph() {
        Document document = composer.compose(facts(SampleProject.shop(), Optional.empty()));

        assertThat(paragraphs(document).getFirst())
                .startsWith("shop-service is a Spring Boot 4.1.1 application on Java 25, with 13 classes.")
                .contains("It serves 5 endpoints, stores 2 types of data, reacts to 2 messages and events,"
                        + " runs 2 scheduled jobs and uses AI models in 1 class.");
    }

    @Test
    void numbersTheSectionsThatHaveSomethingToSay() {
        Document document = composer.compose(facts(SampleProject.shop(), Optional.empty()));

        assertThat(sections(document))
                .containsExactly(
                        "1. Overview",
                        "2. System context",
                        "3. Architecture",
                        "4. How it works",
                        "5. API",
                        "6. Data model",
                        "7. Messages, events and scheduled jobs",
                        "8. Integrations",
                        "9. Security",
                        "10. AI",
                        "11. About this document");
    }

    @Test
    void leavesOutSectionsWithNothingToSay() {
        SampleProject library = SampleProject.empty()
                .java("com/acme/text/Words.java", "package com.acme.text;\npublic final class Words {}\n");

        Document document = composer.compose(new ProjectFacts(
                "words",
                DetectedVersions.none(),
                BuildTool.UNKNOWN,
                0,
                ArchitectureReport.of(library.graph(), 0),
                library.design(),
                Optional.empty()));

        assertThat(sections(document)).containsExactly("1. Overview", "2. Architecture", "3. About this document");
        assertThat(paragraphs(document).getFirst()).isEqualTo("words is a Java application, with 1 class.");
        assertThat(cells(document)).doesNotContain("Build tool");
    }

    @Test
    void drawsTheApplicationAmongItsNeighbours() {
        Document document = composer.compose(facts(SampleProject.shop(), Optional.empty()));

        Diagram context = figures(document).getFirst().diagram();
        assertThat(context.nodes())
                .extracting(Diagram.Node::label)
                .containsExactly(
                        "Clients",
                        "Kafka",
                        "shop-service",
                        "PostgreSQL",
                        "Redis",
                        "Ollama",
                        "OpenAI",
                        "Vector store",
                        "Other services");
        assertThat(context.edges())
                .contains(
                        new Diagram.Edge("clients", "application", "requests", false),
                        new Diagram.Edge("Kafka", "application", "messages", false),
                        new Diagram.Edge("application", "Kafka", "publishes", false),
                        new Diagram.Edge("application", "PostgreSQL", "reads and writes", false));
    }

    @Test
    void warnsWhenAnApplicationWithEndpointsHasNoSecurityConfiguration() {
        SampleProject open = SampleProject.empty().java("com/acme/Api.java", """
                package com.acme;

                import org.springframework.web.bind.annotation.GetMapping;
                import org.springframework.web.bind.annotation.RestController;

                @RestController
                class Api {
                    @GetMapping("/hello")
                    String hello() {
                        return "";
                    }
                }
                """);

        Document document = composer.compose(new ProjectFacts(
                "open",
                VERSIONS,
                BuildTool.GRADLE,
                1,
                ArchitectureReport.of(open.graph(), 1),
                open.design(),
                Optional.empty()));

        assertThat(sections(document))
                .containsExactly(
                        "1. Overview",
                        "2. System context",
                        "3. Architecture",
                        "4. API",
                        "5. Security",
                        "6. About this document");
        assertThat(paragraphs(document))
                .anyMatch(text -> text.startsWith("No Spring Security configuration was found"));
    }

    @Test
    void reportsScoreGateAndTheMostSevereFindingsFirst() {
        Finding minor = finding("cleancode.long-method", Category.CLEAN_CODE, Severity.MINOR, "Method is long");
        Finding blocker =
                finding("security.hardcoded-secret", Category.SECURITY, Severity.BLOCKER, "A key is in code.");
        ReportCard report = new ReportCard(
                List.of(
                        result(Category.CLEAN_CODE, CategoryStatus.HINTS, minor),
                        result(Category.SECURITY, CategoryStatus.FAILED, blocker)),
                new Score(40),
                new GateDecision.Block(List.of("1 blocker")),
                List.of());

        Document document = composer.compose(facts(SampleProject.shop(), Optional.of(report)));

        assertThat(sections(document)).contains("11. Code quality and vulnerabilities");
        assertThat(paragraphs(document)).contains("Score: 40 out of 100. The quality gate blocks: 1 blocker.");
        assertThat(bullets(document))
                .containsSubsequence(
                        "BLOCKER security.hardcoded-secret at src/main/java/A.java:3: A key is in code. Fix: Do it"
                                + " right.",
                        "MINOR cleancode.long-method at src/main/java/A.java:3: Method is long. Fix: Do it right.");
    }

    @Test
    void listsOnlyTheFirstFindingsAndCountsTheRest() {
        List<Finding> many = new ArrayList<>();
        for (int at = 0; at < DocumentComposer.LISTED_FINDINGS + 4; at++) {
            many.add(
                    finding("cleancode.long-method", Category.CLEAN_CODE, Severity.MINOR, "Method " + at + " is long"));
        }
        ReportCard report = new ReportCard(
                List.of(new CategoryResult(
                        Category.CLEAN_CODE, CategoryStatus.HINTS, SeverityCounts.of(many), many, 0)),
                new Score(90),
                GateDecision.pass(),
                List.of());

        Document document = composer.compose(facts(SampleProject.shop(), Optional.of(report)));

        assertThat(paragraphs(document))
                .contains("Score: 90 out of 100. The quality gate passes.")
                .anyMatch(text -> text.startsWith("4 more findings are not listed here."));
    }

    @Test
    void saysSoWhenNothingWasFound() {
        ReportCard clean = new ReportCard(
                List.of(new CategoryResult(
                        Category.SECURITY, CategoryStatus.PASSED, SeverityCounts.of(List.of()), List.of(), 0)),
                Score.PERFECT,
                GateDecision.pass(),
                List.of());

        Document document = composer.compose(facts(SampleProject.shop(), Optional.of(clean)));

        assertThat(paragraphs(document)).contains("No findings.");
    }

    private static ProjectFacts facts(SampleProject project, Optional<ReportCard> quality) {
        return new ProjectFacts(
                "shop-service",
                VERSIONS,
                BuildTool.MAVEN,
                1,
                ArchitectureReport.of(project.graph(), 1),
                project.design(),
                quality);
    }

    private static CategoryResult result(Category category, CategoryStatus status, Finding finding) {
        return new CategoryResult(category, status, SeverityCounts.of(List.of(finding)), List.of(finding), 0);
    }

    private static Finding finding(String rule, Category category, Severity severity, String problem) {
        return new Finding(
                RuleId.of(rule),
                category,
                severity,
                Location.of("src/main/java/A.java", LineRange.line(3)),
                new WhatsWrong(problem, "code"),
                new WhyItMatters("It matters.", List.of()),
                HowToFix.withoutPatch("Do it right."),
                Confidence.HIGH,
                FindingSource.RULE);
    }

    private static List<String> sections(Document document) {
        return document.blocks().stream()
                .filter(block -> block instanceof Heading heading && heading.level() == 1)
                .map(block -> ((Heading) block).text())
                .toList();
    }

    private static List<String> paragraphs(Document document) {
        return document.blocks().stream()
                .filter(Paragraph.class::isInstance)
                .map(block -> ((Paragraph) block).text())
                .toList();
    }

    private static List<String> bullets(Document document) {
        return document.blocks().stream()
                .filter(Bullets.class::isInstance)
                .flatMap(block -> ((Bullets) block).items().stream())
                .toList();
    }

    private static List<Figure> figures(Document document) {
        return document.blocks().stream()
                .filter(Figure.class::isInstance)
                .map(Figure.class::cast)
                .toList();
    }

    private static List<String> cells(Document document) {
        List<String> cells = new ArrayList<>();
        for (Block block : document.blocks()) {
            if (block instanceof Table table) {
                table.rows().forEach(cells::addAll);
            }
        }
        return cells;
    }
}
