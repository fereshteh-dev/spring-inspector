package io.github.fereshtehdev.springinspector.document.render;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.fereshtehdev.springinspector.document.content.Block;
import io.github.fereshtehdev.springinspector.document.content.Block.Bullets;
import io.github.fereshtehdev.springinspector.document.content.Block.Column;
import io.github.fereshtehdev.springinspector.document.content.Block.Figure;
import io.github.fereshtehdev.springinspector.document.content.Block.Heading;
import io.github.fereshtehdev.springinspector.document.content.Block.Paragraph;
import io.github.fereshtehdev.springinspector.document.content.Block.Table;
import io.github.fereshtehdev.springinspector.document.content.Diagram;
import io.github.fereshtehdev.springinspector.document.content.Document;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts.FontName;
import org.apache.pdfbox.pdmodel.interactive.documentnavigation.outline.PDOutlineItem;
import org.apache.pdfbox.text.PDFTextStripper;
import org.junit.jupiter.api.Test;

class PdfWriterTest {

    @Test
    void writesAPdfWithTheDocumentsText() throws IOException {
        try (PDDocument pdf = Loader.loadPDF(PdfWriter.write(Samples.document()))) {
            String text = new PDFTextStripper().getText(pdf);

            assertThat(pdf.getDocumentInformation().getTitle()).isEqualTo("shop: project document");
            assertThat(text)
                    .contains("shop: project document")
                    .contains("Generated by Spring Inspector 1.0 on 2026-11-12")
                    .contains("1. Overview")
                    .contains("Building blocks")
                    .contains("First point")
                    .contains("com.acme.OrderController")
                    .contains("<script>alert('x')</script>")
                    .contains("repository")
                    .contains("5 classes")
                    .contains("Parts of <the> code base")
                    .contains("Page 1 of 1");
        }
    }

    @Test
    void bookmarksEverySection() throws IOException {
        try (PDDocument pdf = Loader.loadPDF(PdfWriter.write(Samples.document()))) {
            List<String> bookmarks = new ArrayList<>();
            for (PDOutlineItem item :
                    pdf.getDocumentCatalog().getDocumentOutline().children()) {
                bookmarks.add(item.getTitle());
            }

            assertThat(bookmarks).containsExactly("1. Overview", "2. Architecture");
        }
    }

    @Test
    void continuesLongTablesOnNewPagesAndRepeatsTheirTitles() throws IOException {
        List<List<String>> rows = new ArrayList<>();
        for (int at = 0; at < 200; at++) {
            rows.add(List.of("row " + at, "com.acme.orders.internal.persistence.OrderRepositoryAdapter" + at));
        }
        Document document = new Document(
                "long",
                "subtitle",
                List.of(new Table(List.of(Column.text("Name", 1), Column.code("Component", 1)), rows)));

        try (PDDocument pdf = Loader.loadPDF(PdfWriter.write(document))) {
            PDFTextStripper stripper = new PDFTextStripper();
            String text = stripper.getText(pdf);
            stripper.setStartPage(2);
            stripper.setEndPage(2);

            assertThat(pdf.getNumberOfPages()).isGreaterThan(2);
            assertThat(text).contains("row 0").contains("row 199").contains("Page 2 of " + pdf.getNumberOfPages());
            assertThat(stripper.getText(pdf)).startsWith("Name Component");
        }
    }

    @Test
    void startsANewPageWhenTextReachesTheFoot() throws IOException {
        List<Block> blocks = new ArrayList<>();
        for (int at = 0; at < 30; at++) {
            blocks.add(new Heading(at % 3 == 0 ? 1 : 2, "Heading " + at));
            blocks.add(new Paragraph("Sentence number " + at + " of a long paragraph. ".repeat(12)));
            blocks.add(new Bullets(List.of("One " + "word ".repeat(40), "Two")));
        }

        try (PDDocument pdf = Loader.loadPDF(PdfWriter.write(new Document("many", "pages", blocks)))) {
            assertThat(pdf.getNumberOfPages()).isGreaterThan(3);
            assertThat(new PDFTextStripper().getText(pdf)).contains("Heading 29");
        }
    }

    @Test
    void shrinksAFigureThatIsWiderThanThePageAndKeepsItWithItsHeading() throws IOException {
        List<Diagram.Node> nodes = new ArrayList<>();
        List<Diagram.Edge> edges = new ArrayList<>();
        for (int at = 0; at < 12; at++) {
            nodes.add(new Diagram.Node("n" + at, "component number " + at, "detail"));
            if (at > 0) {
                edges.add(new Diagram.Edge("n" + (at - 1), "n" + at, "uses", at % 2 == 0));
            }
        }
        List<Block> blocks = new ArrayList<>();
        blocks.add(new Paragraph("Filler. ".repeat(900)));
        blocks.add(new Heading(1, "1. Wide"));
        blocks.add(new Paragraph("Introduction."));
        blocks.add(new Figure(new Diagram(nodes, edges), "A long chain"));

        try (PDDocument pdf = Loader.loadPDF(PdfWriter.write(new Document("wide", "figure", blocks)))) {
            PDFTextStripper stripper = new PDFTextStripper();
            stripper.setStartPage(pdf.getNumberOfPages());

            assertThat(stripper.getText(pdf))
                    .contains("1. Wide")
                    .contains("Introduction.")
                    .contains("component number 11")
                    .contains("A long chain");
        }
    }

    @Test
    void replacesCharactersTheBuiltInFontsDoNotHave() {
        assertThat(PdfWriter.printable("a → b\tc\nd … “q” café سلام •")).isEqualTo("a -> b c d ... \"q\" café ???? •");
    }

    @Test
    void cutsWordsThatAreWiderThanTheLineAfterADotWhenItCan() throws IOException {
        PDType1Font font = new PDType1Font(FontName.COURIER);

        List<String> lines = PdfWriter.wrap("see com.acme.orders.OrderRepositoryAdapter now", font, 10, 120);

        assertThat(lines).containsExactly("see", "com.acme.orders.", "OrderRepositoryAdapt", "er now");
        assertThat(PdfWriter.wrap("", font, 10, 120)).containsExactly("");
    }
}
