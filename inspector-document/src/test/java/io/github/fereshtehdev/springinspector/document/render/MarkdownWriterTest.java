package io.github.fereshtehdev.springinspector.document.render;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.fereshtehdev.springinspector.document.content.Block.Figure;
import io.github.fereshtehdev.springinspector.document.content.Diagram;
import io.github.fereshtehdev.springinspector.document.content.Document;
import java.util.List;
import org.junit.jupiter.api.Test;

class MarkdownWriterTest {

    private final String markdown = MarkdownWriter.write(Samples.document());

    @Test
    void writesTitleHeadingsParagraphsAndBullets() {
        assertThat(markdown)
                .startsWith("# shop: project document\n\n_Generated by Spring Inspector 1.0 on 2026-11-12_\n")
                .contains("\n## 1. Overview\n")
                .contains("\n### Building blocks\n")
                .contains("\n- First point\n");
    }

    @Test
    void writesTablesWithCodeColumnsAsCode() {
        assertThat(markdown).contains("| Kind | Class |\n|---|---|\n| Controller | `com.acme.OrderController` |\n");
    }

    @Test
    void escapesTextThatWouldBecomeFormattingLinksOrHtml() {
        assertThat(markdown)
                .contains("&lt;script&gt;alert('x')&lt;/script&gt; &amp; \"quoted\" \\| \\`code\\` \\*bold\\*"
                        + " \\[link\\](http://x)");
    }

    @Test
    void keepsACodeCellFromEndingItsColumnOrItsCodeSpan() {
        assertThat(markdown)
                .contains("| `<script>alert('x')</script> & \"quoted\" \\| 'code' *bold* [link](http://x)` |");
    }

    @Test
    void drawsFiguresAsMermaidWithProblemArrowsInRed() {
        assertThat(markdown).contains("""
                        ```mermaid
                        flowchart LR
                            n0["web<br/>3 classes"]
                            n1["service<br/>5 classes"]
                            n2["repository"]
                            n0 -->|"3"| n1
                            n1 -->|"2"| n2
                            n2 -->|"1"| n1
                            linkStyle 2 stroke:#d33,stroke-width:2px
                        ```

                        _Parts of &lt;the&gt; code base_
                        """);
    }

    @Test
    void keepsLabelsFromBreakingOutOfTheDiagram() {
        Diagram diagram = new Diagram(
                List.of(new Diagram.Node("a", "say \"hi\"]\nend", "<b>"), new Diagram.Node("a", "duplicate", "")),
                List.of(new Diagram.Edge("a", "missing", "", false), new Diagram.Edge("a", "a", "", false)));

        String figure = MarkdownWriter.write(new Document("t", "s", List.of(new Figure(diagram, "caption"))));

        assertThat(figure)
                .contains("n0[\"say #quot;hi#quot;] end<br/>#lt;b#gt;\"]")
                .contains("    n0 --> n0\n")
                .doesNotContain("duplicate")
                .doesNotContain("missing");
    }
}
