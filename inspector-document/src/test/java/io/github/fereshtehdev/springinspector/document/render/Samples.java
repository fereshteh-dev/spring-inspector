package io.github.fereshtehdev.springinspector.document.render;

import io.github.fereshtehdev.springinspector.document.content.Block.Bullets;
import io.github.fereshtehdev.springinspector.document.content.Block.Column;
import io.github.fereshtehdev.springinspector.document.content.Block.Figure;
import io.github.fereshtehdev.springinspector.document.content.Block.Heading;
import io.github.fereshtehdev.springinspector.document.content.Block.Paragraph;
import io.github.fereshtehdev.springinspector.document.content.Block.Table;
import io.github.fereshtehdev.springinspector.document.content.Diagram;
import io.github.fereshtehdev.springinspector.document.content.Document;
import java.util.List;

final class Samples {

    static final String HOSTILE = "<script>alert('x')</script> & \"quoted\" | `code` *bold* [link](http://x)";

    private Samples() {}

    static Diagram diagram() {
        return new Diagram(
                List.of(
                        new Diagram.Node("web", "web", "3 classes"),
                        new Diagram.Node("service", "service", "5 classes"),
                        new Diagram.Node("repository", "repository", "")),
                List.of(
                        new Diagram.Edge("web", "service", "3", false),
                        new Diagram.Edge("service", "repository", "2", false),
                        new Diagram.Edge("repository", "service", "1", true)));
    }

    /** One block of every kind, with text that would break out of each format if it were not escaped. */
    static Document document() {
        return new Document(
                "shop: project document",
                "Generated by Spring Inspector 1.0 on 2026-11-12",
                List.of(
                        new Heading(1, "1. Overview"),
                        new Paragraph("The shop sells things. " + HOSTILE),
                        new Heading(2, "Building blocks"),
                        new Bullets(List.of("First point", "Second point with " + HOSTILE)),
                        new Table(
                                List.of(Column.text("Kind", 2), Column.code("Class", 3)),
                                List.of(List.of("Controller", "com.acme.OrderController"), List.of(HOSTILE, HOSTILE))),
                        new Heading(1, "2. Architecture"),
                        new Figure(diagram(), "Parts of <the> code base")));
    }
}
