/**
 * Writes a project's document: what the project is, how it is built and how it works, how it is secured, how it
 * uses AI, and what should be fixed. Sections with nothing to say are left out.
 */
public final class DocumentComposer {

    static final int LISTED_FINDINGS = 25;
    static final int DIAGRAM_PARTS = 30;

    private final String inspectorVersion;
    private final Clock clock;

    public DocumentComposer(String inspectorVersion, Clock clock) {
        this.inspectorVersion = inspectorVersion;
        this.clock = clock;
    }

    public Document compose(ProjectFacts facts) {
        Sections sections = new Sections();
        overview(facts, sections);
        systemContext(facts, sections);
        architecture(facts.architecture(), sections);
        flows(facts.design(), sections);
        api(facts.design(), sections);
        dataModel(facts.design(), sections);
        messaging(facts.design(), sections);
        integrations(facts.design(), sections);
        security(facts.design(), sections);
        ai(facts.design().ai(), sections);
        facts.quality().ifPresent(report -> quality(report, sections));
        suggestions(facts.architecture(), sections);
        sections.section("About this document");
        sections.add(new Paragraph("Spring Inspector wrote this document by reading the project's source code, build"
                + " files and settings on this machine. It did not compile or run the project and sent nothing"
                + " over the network. What cannot be seen in the source, such as settings supplied at run time, is"
                + " not described."));
        return new Document(
                facts.name() + ": project document",
                "Generated by Spring Inspector " + inspectorVersion + " on " + LocalDate.now(clock),
                sections.blocks);
    }

    private static void overview(ProjectFacts facts, Sections sections) {
        SystemDesign design = facts.design();
        sections.section("Overview");
        sections.add(new Paragraph(summary(facts)));
        List<List<String>> rows = new ArrayList<>();
        DetectedVersions versions = facts.versions();
        versions.java().ifPresent(java -> rows.add(List.of("Java", String.valueOf(java.major()))));
        versions.springBoot().ifPresent(boot -> rows.add(List.of("Spring Boot", boot.toString())));
        versions.springAi().ifPresent(ai -> rows.add(List.of("Spring AI", ai.toString())));
        if (facts.buildTool() != BuildTool.UNKNOWN) {
            rows.add(List.of("Build tool", buildTool(facts.buildTool())));
        }
        rows.add(List.of("Build modules", String.valueOf(Math.max(1, facts.modules()))));
        rows.add(List.of("Classes", String.valueOf(facts.architecture().classes())));
        if (!facts.architecture().rootPackage().isEmpty()) {
            rows.add(List.of("Root package", facts.architecture().rootPackage()));
        }
        if (!design.applications().isEmpty()) {
            rows.add(List.of("Application class", String.join(", ", design.applications())));
        }
        design.settings().serverPort().ifPresent(port -> rows.add(List.of("HTTP port", port)));
        if (!design.settings().dataStores().isEmpty()) {
            rows.add(List.of("Data stores", String.join(", ", design.settings().dataStores())));
        }
        if (!design.settings().profiles().isEmpty()) {
            rows.add(List.of("Profiles", String.join(", ", design.settings().profiles())));
        }
        sections.add(new Table(List.of(Column.text("Property", 1), Column.text("Value", 3)), rows));
        if (!design.components().isEmpty()) {
            sections.part("Building blocks");
            sections.add(new Table(
                    List.of(Column.text("Kind", 3), Column.text("Classes", 1)),
                    design.components().stream()
                            .map(count -> List.of(count.role(), String.valueOf(count.classes())))
                            .toList()));
        }
        if (!design.technologies().isEmpty()) {
            sections.part("Technologies");
            sections.add(new Table(
                    List.of(Column.text("Technology", 3), Column.text("Classes that use it", 1)),
                    design.technologies().stream()
                            .map(technology -> List.of(technology.name(), String.valueOf(technology.classes())))
                            .toList()));
        }
    }

    private static String summary(ProjectFacts facts) {
        SystemDesign design = facts.design();
        DetectedVersions versions = facts.versions();
        StringBuilder text = new StringBuilder(facts.name()).append(" is a ");
        text.append(
                versions.springBoot().map(boot -> "Spring Boot " + boot + " ").orElse("Java "));
        text.append("application");
        versions.java().ifPresent(java -> text.append(" on Java ").append(java.major()));
        text.append(", with ")
                .append(plural(facts.architecture().classes(), "class", "classes"))
                .append(".");
        List<String> styles = facts.architecture().styles().stream()
                .map(match -> match.style().title())
                .toList();
        if (!styles.isEmpty()) {
            text.append(" Its structure follows: ")
                    .append(String.join(", ", styles))
                    .append(".");
        }
        List<String> does = new ArrayList<>();
        if (!design.endpoints().isEmpty()) {
            does.add("serves " + plural(design.endpoints().size(), "endpoint", "endpoints"));
        }
        if (!design.entities().isEmpty()) {
            does.add("stores " + plural(design.entities().size(), "type", "types") + " of data");
        }
        if (!design.listeners().isEmpty()) {
            does.add("reacts to " + plural(design.listeners().size(), "message or event", "messages and events"));
        }
        if (!design.jobs().isEmpty()) {
            does.add("runs " + plural(design.jobs().size(), "scheduled job", "scheduled jobs"));
        }
        if (!design.ai().components().isEmpty()) {
            does.add("uses AI models in " + plural(design.ai().components().size(), "class", "classes"));
        }
        if (!does.isEmpty()) {
            text.append(" It ").append(sentenceList(does)).append(".");
        }
        return text.toString();
    }

    private static void systemContext(ProjectFacts facts, Sections sections) {
        Diagram diagram = SystemContext.of(facts);
        if (diagram.nodes().size() < 2) {
            return;
        }
        sections.section("System context");
        sections.add(new Paragraph(
                "The application in the middle, with who calls it on the left and what it depends on on the right."));
        sections.add(new Figure(diagram, "The application and the systems around it"));
    }

    private static void architecture(ArchitectureReport report, Sections sections) {
        sections.section("Architecture");
        if (report.styles().isEmpty()) {
            sections.add(new Paragraph("No common architecture style was recognised in the package structure."));
        } else {
            sections.add(new Table(
                    List.of(
                            Column.text("Style", 2),
                            Column.text("What it means", 4),
                            Column.text("Confidence", 1),
                            Column.text("Recognised from", 4)),
                    report.styles().stream()
                            .map(match -> List.of(
                                    match.style().title(),
                                    match.style().description(),
                                    match.confidence(),
                                    String.join("; ", match.evidence())))
                            .toList()));
        }
        if (report.parts().size() > 1 && report.parts().size() <= DIAGRAM_PARTS) {
            sections.part("Parts and their dependencies");
            sections.add(new Paragraph("An arrow from A to B means classes in A use classes in B; the number is how"
                    + " many classes do. Red arrows are dependencies in both directions."));
            sections.add(new Figure(partsDiagram(report.parts()), "Parts of the code base"));
        } else if (report.parts().size() > DIAGRAM_PARTS) {
            sections.part("Parts and their dependencies");
            sections.add(new Table(
                    List.of(Column.code("Part", 2), Column.text("Classes", 1), Column.code("Uses", 5)),
                    report.parts().stream()
                            .map(part -> List.of(
                                    part.name(),
                                    String.valueOf(part.classes()),
                                    String.join(", ", part.dependsOn().keySet())))
                            .toList()));
        }
        if (!report.cycles().isEmpty()) {
            sections.part("Dependency cycles");
            sections.add(new Paragraph("These packages depend on each other in a circle, so none of them can be"
                    + " understood, tested or changed alone."));
            sections.add(new Bullets(report.cycles().stream()
                    .map(cycle -> String.join(" <-> ", cycle))
                    .toList()));
        }
        if (!report.hotspots().isEmpty()) {
            sections.part("Classes that do too much");
            sections.add(new Table(
                    List.of(Column.code("Class", 5), Column.text("Used by", 1), Column.text("Uses", 1)),
                    report.hotspots().stream()
                            .map(hotspot -> List.of(
                                    hotspot.type(), String.valueOf(hotspot.usedBy()), String.valueOf(hotspot.uses())))
                            .toList()));
        }
    }

    private static Diagram partsDiagram(List<Part> parts) {
        List<Diagram.Node> nodes = parts.stream()
                .map(part -> new Diagram.Node(part.name(), part.name(), plural(part.classes(), "class", "classes")))
                .toList();
        List<Diagram.Edge> edges = new ArrayList<>();
        for (Part part : parts) {
            part.dependsOn().forEach((target, count) -> {
                boolean mutual = parts.stream()
                        .anyMatch(other ->
                                other.name().equals(target) && other.dependsOn().containsKey(part.name()));
                edges.add(new Diagram.Edge(part.name(), target, String.valueOf(count), mutual));
            });
        }
        return new Diagram(nodes, edges);
    }

    private static void flows(SystemDesign design, Sections sections) {
        if (design.flows().isEmpty()) {
            return;
        }
        sections.section("How it works");
        sections.add(new Paragraph("What happens when a request, a message or a timer reaches the application: the"
                + " entry point, the components it calls, and the components those call in turn."));
        sections.add(new Table(
                List.of(
                        Column.code("Entry point", 3),
                        Column.text("Started by", 1),
                        Column.code("Calls", 4),
                        Column.code("Which call", 4)),
                design.flows().stream()
                        .map(flow -> List.of(
                                flow.entry(),
                                flow.trigger(),
                                String.join(", ", flow.direct()),
                                String.join(", ", flow.indirect())))
                        .toList()));
    }

    private static void api(SystemDesign design, Sections sections) {
        if (design.endpoints().isEmpty()) {
            return;
        }
        sections.section("API");
        sections.add(new Table(
                List.of(
                        Column.text("Method", 1),
                        Column.code("Path", 4),
                        Column.code("Handled by", 4),
                        Column.code("Request body", 2),
                        Column.code("Response", 2),
                        Column.code("Access rule", 3)),
                design.endpoints().stream()
                        .map(endpoint -> List.of(
                                endpoint.method(),
                                endpoint.path(),
                                endpoint.handler(),
                                endpoint.requestBody(),
                                endpoint.response(),
                                endpoint.access()))
                        .toList()));
        sections.add(new Paragraph("An empty access rule means the handler has no method security annotation; the"
                + " rules of the security filter chain still apply."));
    }

    private static void dataModel(SystemDesign design, Sections sections) {
        if (design.entities().isEmpty()) {
            return;
        }
        sections.section("Data model");
        sections.add(new Table(
                List.of(
                        Column.code("Type", 3),
                        Column.code("Table or collection", 3),
                        Column.code("Id", 2),
                        Column.text("Fields", 1),
                        Column.code("Relations", 5)),
                design.entities().stream()
                        .map(entity -> List.of(
                                entity.name(),
                                entity.store(),
                                entity.idField(),
                                String.valueOf(entity.fields()),
                                entity.relations().stream()
                                        .map(relation ->
                                                relation.kind() + " " + relation.field() + " -> " + relation.target())
                                        .collect(Collectors.joining("; "))))
                        .toList()));
        Diagram relations = relationDiagram(design.entities());
        if (!relations.edges().isEmpty() && relations.nodes().size() <= DIAGRAM_PARTS) {
            sections.add(new Figure(relations, "Stored types and how they refer to each other"));
        }
    }

    private static Diagram relationDiagram(List<EntityModel> entities) {
        List<String> names = entities.stream().map(EntityModel::name).toList();
        List<Diagram.Edge> edges = new ArrayList<>();
        for (EntityModel entity : entities) {
            for (Relation relation : entity.relations()) {
                if (names.contains(relation.target()) && !relation.target().equals(entity.name())) {
                    edges.add(new Diagram.Edge(entity.name(), relation.target(), relation.kind(), false));
                }
            }
        }
        List<Diagram.Node> nodes = entities.stream()
                .filter(entity -> edges.stream()
                        .anyMatch(edge ->
                                edge.from().equals(entity.name()) || edge.to().equals(entity.name())))
                .map(entity -> new Diagram.Node(entity.name(), entity.name(), entity.store()))
                .toList();
        return new Diagram(nodes, edges);
    }

    private static void messaging(SystemDesign design, Sections sections) {
        if (design.listeners().isEmpty() && design.jobs().isEmpty()) {
            return;
        }
        sections.section("Messages, events and scheduled jobs");
        if (!design.listeners().isEmpty()) {
            sections.add(new Table(
                    List.of(Column.text("Listens to", 2), Column.code("Source", 4), Column.code("Handled by", 4)),
                    design.listeners().stream()
                            .map(listener -> List.of(listener.kind(), listener.source(), listener.handler()))
                            .toList()));
        }
        if (!design.jobs().isEmpty()) {
            sections.add(new Table(
                    List.of(Column.code("Schedule", 3), Column.code("Job", 5)),
                    design.jobs().stream()
                            .map(job -> List.of(job.schedule(), job.handler()))
                            .toList()));
        }
    }

    private static void integrations(SystemDesign design, Sections sections) {
        if (design.integrations().isEmpty()) {
            return;
        }
        sections.section("Integrations");
        sections.add(new Paragraph("Components that talk to something outside the application's own code."));
        sections.add(new Table(
                List.of(Column.code("Component", 3), Column.text("Through", 3), Column.code("Target", 4)),
                design.integrations().stream()
                        .map(integration ->
                                List.of(integration.component(), integration.technology(), integration.detail()))
                        .toList()));
    }

    private static void security(SystemDesign design, Sections sections) {
        SecurityDesign security = design.security();
        boolean usesSpringSecurity = design.technologies().stream()
                .anyMatch(technology -> technology.name().equals("Spring Security"));
        if (security.isEmpty() && (usesSpringSecurity || design.endpoints().isEmpty())) {
            return;
        }
        sections.section("Security");
        if (security.isEmpty()) {
            sections.add(new Paragraph("No Spring Security configuration was found in the source. Unless a gateway"
                    + " in front of the application protects it, every endpoint is open to anyone who can reach"
                    + " it."));
            return;
        }
        if (!security.features().isEmpty()) {
            sections.add(new Bullets(security.features()));
        }
        if (!security.rules().isEmpty()) {
            sections.part("Who may call what");
            sections.add(new Paragraph("Rules are tried from top to bottom; the first one that matches decides."));
            sections.add(new Table(
                    List.of(Column.code("Requests", 4), Column.text("Allowed for", 3), Column.code("Defined in", 3)),
                    security.rules().stream()
                            .map(rule -> List.of(rule.requests(), rule.access(), rule.definedIn()))
                            .toList()));
        }
        if (security.methodRules() > 0) {
            sections.add(
                    new Paragraph(plural(security.methodRules(), "class or method carries", "classes and methods carry")
                            + " a method security annotation such as @PreAuthorize."));
        }
    }

    private static void ai(AiDesign ai, Sections sections) {
        if (ai.isEmpty()) {
            return;
        }
        sections.section("AI");
        List<String> facts = new ArrayList<>();
        ai.models().forEach(model -> facts.add("Model setting: " + model));
        if (!ai.vectorStores().isEmpty()) {
            facts.add("Vector stores: " + String.join(", ", ai.vectorStores()));
        }
        if (!ai.advisors().isEmpty()) {
            facts.add("Advisors around model calls: " + String.join(", ", ai.advisors()));
        }
        if (!facts.isEmpty()) {
            sections.add(new Bullets(facts));
        }
        if (!ai.components().isEmpty()) {
            sections.part("Where models are used");
            sections.add(new Table(
                    List.of(Column.code("Component", 3), Column.text("Uses", 5)),
                    ai.components().stream()
                            .map(component -> List.of(component.component(), String.join(", ", component.uses())))
                            .toList()));
        }
        if (!ai.tools().isEmpty()) {
            sections.part("Tools the model can call");
            sections.add(new Paragraph("Each tool is code the model decides to run. Check that every tool is safe to"
                    + " call with any arguments, for any user."));
            sections.add(new Table(
                    List.of(
                            Column.text("Kind", 1),
                            Column.code("Name", 3),
                            Column.text("Description", 5),
                            Column.code("Defined in", 3)),
                    ai.tools().stream()
                            .map(tool -> List.of(tool.kind(), tool.name(), tool.description(), tool.definedIn()))
                            .toList()));
        }
    }

    private static void quality(ReportCard report, Sections sections) {
        sections.section("Code quality and vulnerabilities");
        String gate = switch (report.gate()) {
            case GateDecision.Pass pass -> "The quality gate passes.";
            case GateDecision.Block block -> "The quality gate blocks: " + String.join("; ", block.reasons()) + ".";
        };
        sections.add(new Paragraph("Score: " + report.score().value() + " out of 100. " + gate));
        sections.add(new Table(
                List.of(
                        Column.text("Category", 3),
                        Column.text("Result", 2),
                        Column.text("Blocker", 1),
                        Column.text("Major", 1),
                        Column.text("Minor", 1),
                        Column.text("Info", 1)),
                report.categories().stream().map(DocumentComposer::row).toList()));
        List<Finding> findings = report.categories().stream()
                .flatMap(category -> category.findings().stream())
                .sorted(Comparator.comparing(Finding::severity)
                        .thenComparing(finding -> finding.location().toString()))
                .toList();
        if (findings.isEmpty()) {
            sections.add(new Paragraph("No findings."));
            return;
        }
        sections.part("What to fix first");
        sections.add(new Bullets(findings.stream()
                .limit(LISTED_FINDINGS)
                .map(DocumentComposer::advice)
                .toList()));
        if (findings.size() > LISTED_FINDINGS) {
            sections.add(new Paragraph((findings.size() - LISTED_FINDINGS)
                    + " more findings are not listed here. Run spring-inspector check --all to see every one."));
        }
    }

    private static String advice(Finding finding) {
        String problem = finding.whatsWrong().description().strip();
        return finding.severity() + " " + finding.ruleId() + " at " + finding.location() + ": " + problem
                + (problem.endsWith(".") ? "" : ".") + " Fix: "
                + finding.howToFix().explanation();
    }

    private static List<String> row(CategoryResult result) {
        String status = switch (result.status()) {
            case PASSED -> "passed";
            case FAILED -> "has issues";
            case HINTS -> "has hints";
        };
        return List.of(
                title(result.category()),
                status,
                String.valueOf(result.counts().blocker()),
                String.valueOf(result.counts().major()),
                String.valueOf(result.counts().minor()),
                String.valueOf(result.counts().info()));
    }

    private static void suggestions(ArchitectureReport report, Sections sections) {
        if (report.suggestions().isEmpty()) {
            return;
        }
        sections.section("Suggestions for a cleaner structure");
        report.suggestions().forEach(suggestion -> {
            sections.part(suggestion.title());
            sections.add(new Paragraph(suggestion.why()));
            if (!suggestion.steps().isEmpty()) {
                sections.add(new Bullets(
                        suggestion.steps().stream().map(String::strip).toList()));
            }
        });
    }

    private static String title(Category category) {
        return switch (category) {
            case SECURITY -> "Security";
            case SPRING_BOOT -> "Spring Boot";
            case SPRING_AI -> "Spring AI";
            case CLEAN_CODE -> "Clean code";
            case ARCHITECTURE -> "Architecture";
            case MIGRATION -> "Migration";
        };
    }

    private static String buildTool(BuildTool tool) {
        return switch (tool) {
            case MAVEN -> "Maven";
            case GRADLE -> "Gradle";
            case UNKNOWN -> "not recognised";
        };
    }

    static String plural(int count, String one, String many) {
        return count + " " + (count == 1 ? one : many);
    }

    private static String sentenceList(List<String> items) {
        if (items.size() == 1) {
            return items.getFirst();
        }
        return String.join(", ", items.subList(0, items.size() - 1)) + " and " + items.getLast();
    }

    /** The blocks written so far, with sections numbered as they are added. */
    private static final class Sections {

        private final List<Block> blocks = new ArrayList<>();
        private int number;

        void section(String title) {
            number++;
            blocks.add(new Heading(1, number + ". " + title));
        }

        void part(String title) {
            blocks.add(new Heading(2, title));
        }

        void add(Block block) {
            blocks.add(block);
        }
    }
}
