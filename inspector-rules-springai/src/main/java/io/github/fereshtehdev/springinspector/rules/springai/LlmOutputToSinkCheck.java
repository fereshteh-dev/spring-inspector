package io.github.fereshtehdev.springinspector.rules.springai;

import com.github.javaparser.ast.Node;
import com.github.javaparser.ast.expr.ArrayCreationExpr;
import com.github.javaparser.ast.expr.Expression;
import com.github.javaparser.ast.expr.MethodCallExpr;
import com.github.javaparser.ast.expr.ObjectCreationExpr;
import io.github.fereshtehdev.springinspector.core.domain.Category;
import io.github.fereshtehdev.springinspector.core.domain.Confidence;
import io.github.fereshtehdev.springinspector.core.domain.Finding;
import io.github.fereshtehdev.springinspector.core.domain.HowToFix;
import io.github.fereshtehdev.springinspector.core.domain.Reference;
import io.github.fereshtehdev.springinspector.core.domain.RuleId;
import io.github.fereshtehdev.springinspector.core.domain.Severity;
import io.github.fereshtehdev.springinspector.core.domain.WhyItMatters;
import io.github.fereshtehdev.springinspector.javamodel.JavaCheck;
import io.github.fereshtehdev.springinspector.javamodel.JavaFile;
import io.github.fereshtehdev.springinspector.javamodel.StringExpressions;
import java.net.URI;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * Text generated by a model ({@code ...call().content()}) passed, directly or through local variables, string
 * building or array elements, to SQL, a shell, file paths or class loading.
 */
public final class LlmOutputToSinkCheck extends JavaCheck {

    static final RuleId ID = RuleId.of("springai.llm-output-to-sink");

    private static final Map<String, String> SINK_METHODS = Map.ofEntries(
            Map.entry("query", "SQL"),
            Map.entry("queryForList", "SQL"),
            Map.entry("queryForObject", "SQL"),
            Map.entry("update", "SQL"),
            Map.entry("execute", "SQL"),
            Map.entry("sql", "SQL"),
            Map.entry("createQuery", "SQL"),
            Map.entry("createNativeQuery", "SQL"),
            Map.entry("prepareStatement", "SQL"),
            Map.entry("executeQuery", "SQL"),
            Map.entry("executeUpdate", "SQL"),
            Map.entry("exec", "a shell command"),
            Map.entry("forName", "class loading"),
            Map.entry("eval", "a script engine"));
    private static final Set<String> PATH_TYPES = Set.of("java.nio.file.Path", "java.nio.file.Paths");
    private static final Set<String> SINK_TYPES = Set.of("java.lang.ProcessBuilder", "java.io.File");
    private static final int MAX_DEPTH = 6;

    private static final WhyItMatters WHY = new WhyItMatters(
            "Model output is untrusted input: it follows whatever the prompt, the user or a retrieved document steered"
                    + " it to say. Used as code, a query or a path, it can run commands, read or delete data, or reach"
                    + " files outside the intended directory.",
            List.of(new Reference(
                    "OWASP Top 10 for LLM Applications: LLM05 Improper Output Handling",
                    URI.create("https://genai.owasp.org/llmrisk/llm052025-improper-output-handling/"))));

    private static final HowToFix FIX = HowToFix.withoutPatch(
            "Have the model return structured output (.entity(Record.class)), validate every field against what is"
                    + " allowed, and pass the values as bind parameters or choices from an allow-list, never as code,"
                    + " queries or paths.");

    @Override
    public RuleId id() {
        return ID;
    }

    @Override
    public Category category() {
        return Category.SPRING_AI;
    }

    @Override
    protected List<Finding> inspect(JavaFile file) {
        List<Finding> findings = new ArrayList<>();
        for (MethodCallExpr call : file.unit().findAll(MethodCallExpr.class)) {
            sink(file, call)
                    .ifPresent(sink ->
                            report(file, call, sink, call.getArguments()).ifPresent(findings::add));
        }
        for (ObjectCreationExpr creation : file.unit().findAll(ObjectCreationExpr.class)) {
            String type = creation.getType().getNameWithScope();
            if (SINK_TYPES.stream().anyMatch(sinkType -> file.refersTo(type, sinkType))) {
                String sink = type.endsWith("ProcessBuilder") ? "a shell command" : "a file path";
                report(file, creation, sink, creation.getArguments()).ifPresent(findings::add);
            }
        }
        return findings;
    }

    private static Optional<String> sink(JavaFile file, MethodCallExpr call) {
        boolean pathFactory = (call.getNameAsString().equals("of")
                        || call.getNameAsString().equals("get"))
                && call.getScope()
                        .map(scope -> PATH_TYPES.stream().anyMatch(type -> file.refersTo(scope.toString(), type)))
                        .orElse(false);
        if (pathFactory || call.getNameAsString().equals("resolve")) {
            return Optional.of("a file path");
        }
        return Optional.ofNullable(SINK_METHODS.get(call.getNameAsString()));
    }

    private Optional<Finding> report(JavaFile file, Node use, String sink, List<Expression> arguments) {
        if (arguments.stream().noneMatch(argument -> isModelOutput(argument, 0))) {
            return Optional.empty();
        }
        return Optional.of(
                finding(file, use, Severity.MAJOR, Confidence.HIGH, "Model output is used as " + sink, WHY, FIX));
    }

    /** {@code chat.prompt()...call().content()}, a local holding it, or a string built from it. */
    private static boolean isModelOutput(Expression expression, int depth) {
        if (depth > MAX_DEPTH) {
            return false;
        }
        Expression value = StringExpressions.followLocal(expression);
        if (value instanceof MethodCallExpr call && call.getNameAsString().equals("content") && callsModel(call)) {
            return true;
        }
        if (value instanceof ArrayCreationExpr array && array.getInitializer().isPresent()) {
            return array.getInitializer().get().getValues().stream()
                    .anyMatch(element -> isModelOutput(element, depth + 1));
        }
        return StringExpressions.runtimeValues(value).stream().anyMatch(part -> isModelOutput(part, depth + 1));
    }

    private static boolean callsModel(MethodCallExpr content) {
        Optional<Expression> scope = content.getScope();
        while (scope.isPresent() && scope.get() instanceof MethodCallExpr inner) {
            if (inner.getNameAsString().equals("call") && inner.getArguments().isEmpty()) {
                return true;
            }
            scope = inner.getScope();
        }
        return false;
    }
}
